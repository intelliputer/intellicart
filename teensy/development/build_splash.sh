#!/usr/bin/env bash
# Build the Intellicart startup ROM and regenerate the firmware byte array.
set -euo pipefail

repo_root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
sdk_root=$(CDPATH= cd -- "$repo_root/../sdk1600" && pwd)
splash_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
bin_file=$(mktemp "${TMPDIR:-/tmp}/intellicart-splash.XXXXXX.bin")
list_file=$(mktemp "${TMPDIR:-/tmp}/intellicart-splash.XXXXXX.lst")
trap 'rm -f "$bin_file" "$list_file"' EXIT

cd "$splash_dir"
"$sdk_root/bin/as1600" -o "$bin_file" -l "$list_file" splash.asm
if rg -q 'ERROR -' "$list_file"; then
    printf 'assembly failed; see %s\n' "$list_file" >&2
    exit 1
fi

size=$(wc -c < "$bin_file")
if (( size > 2560 )); then
    printf 'startup ROM is %s bytes; it must not exceed 2560 bytes\n' "$size" >&2
    exit 1
fi

# The firmware always maps 1,280 words.  Pad unused ROM space with zeroes.
truncate -s 2560 "$bin_file"

{
    printf '/*\n * Generated by build_splash.sh from splash.asm.\n * 2,560 bytes (1,280 16-bit words), mapped at $5000 during startup.\n */\n\n'
    xxd -i -n splash "$bin_file" | sed \
        -e 's/^unsigned char splash\[\] = {/unsigned char splash[2560] PROGMEM = {/' \
        -e '/^unsigned int splash_len =/d'
} > splash.h

printf 'Generated %s from splash.asm (%s source bytes, padded to 2560).\n' \
    "$splash_dir/splash.h" "$size"
